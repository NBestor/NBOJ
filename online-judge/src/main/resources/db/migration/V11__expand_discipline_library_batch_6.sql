    sort_order = EXCLUDED.sort_order,
    enabled = EXCLUDED.enabled,
    library_version = EXCLUDED.library_version,
    updated_at = CURRENT_TIMESTAMP;

DO $$
DECLARE
    batch_chars bigint;
BEGIN
    IF EXISTS (SELECT 1 FROM public.informatics_knowledge_nodes) THEN
        IF (SELECT count(*) FROM public.informatics_knowledge_nodes
            WHERE enabled = true AND type = 'KNOWLEDGE_POINT'
              AND library_version = 'informatics-knowledge-discipline-v6') <> 48 THEN
            RAISE EXCEPTION 'V11 expected exactly 48 curated knowledge points';
        END IF;

        IF EXISTS (
            SELECT split_part(code, '.', 1)
            FROM public.informatics_knowledge_nodes
            WHERE enabled = true AND type = 'KNOWLEDGE_POINT'
              AND library_version = 'informatics-knowledge-discipline-v6'
            GROUP BY split_part(code, '.', 1)
            HAVING count(*) <> 8
        ) THEN
            RAISE EXCEPTION 'V11 curated knowledge points must be balanced across six domains';
        END IF;

        IF (SELECT count(*) FROM public.ai_standard_skill_units
            WHERE enabled = true AND library_version = 'informatics-discipline-quality-v6') <> 48
           OR (SELECT count(*) FROM public.ai_standard_mistake_points
               WHERE enabled = true AND library_version = 'informatics-discipline-quality-v6') <> 144
           OR (SELECT count(*) FROM public.ai_standard_improvement_points
               WHERE enabled = true AND library_version = 'informatics-discipline-quality-v6') <> 48
           OR (SELECT count(*) FROM public.ai_standard_application_scenarios
               WHERE enabled = true AND library_version = 'informatics-discipline-application-v2') <> 96 THEN
            RAISE EXCEPTION 'V11 normalized theme pack counts are incomplete';
        END IF;

        IF EXISTS (
            SELECT s.code
            FROM public.ai_standard_skill_units s
            LEFT JOIN public.ai_standard_mistake_points m
              ON m.skill_unit_code = s.code AND m.enabled = true
             AND m.library_version = 'informatics-discipline-quality-v6'
            LEFT JOIN public.ai_standard_improvement_points i
              ON i.skill_unit_code = s.code AND i.enabled = true
             AND i.library_version = 'informatics-discipline-quality-v6'
            LEFT JOIN public.ai_standard_application_scenarios a
              ON a.skill_unit_code = s.code AND a.enabled = true
             AND a.library_version = 'informatics-discipline-application-v2'
            WHERE s.enabled = true AND s.library_version = 'informatics-discipline-quality-v6'
            GROUP BY s.code
            HAVING count(DISTINCT m.code) <> 3
                OR count(DISTINCT i.code) <> 1
                OR count(DISTINCT a.code) <> 2
                OR count(DISTINCT a.context_type) <> 2
        ) THEN
            RAISE EXCEPTION 'V11 contains an incomplete theme pack';
        END IF;

        IF (SELECT count(*) FROM public.ai_standard_library_items
            WHERE enabled = true AND library_version = 'informatics-discipline-quality-v6') <> 240
           OR (SELECT count(*) FROM public.ai_standard_library_legacy_mappings
               WHERE migration_status = 'MAPPED'
                 AND source_version = 'informatics-discipline-quality-v6') <> 240 THEN
            RAISE EXCEPTION 'V11 flat snapshots or legacy mappings are incomplete';
        END IF;

        IF EXISTS (
            SELECT skill_unit_code
            FROM public.ai_standard_mistake_points
            WHERE enabled = true AND library_version = 'informatics-discipline-quality-v6'
            GROUP BY skill_unit_code
            HAVING count(*) <> count(DISTINCT regexp_replace(lower(name), '[[:space:]（）()_-]+', '', 'g'))
                OR count(*) <> count(DISTINCT symptom)
                OR count(*) <> count(DISTINCT repair_strategy)
        ) THEN
            RAISE EXCEPTION 'V11 contains duplicate mistake names, symptoms or repairs inside a theme';
        END IF;

        IF EXISTS (
            SELECT student_task
            FROM public.ai_standard_application_scenarios
            WHERE enabled = true AND library_version = 'informatics-discipline-application-v2'
            GROUP BY student_task HAVING count(*) > 1
        ) OR EXISTS (
            SELECT transfer_pair_code
            FROM public.ai_standard_application_scenarios
            WHERE enabled = true AND library_version = 'informatics-discipline-application-v2'
            GROUP BY transfer_pair_code
            HAVING count(*) <> 2 OR count(DISTINCT context_type) <> 2
        ) THEN
            RAISE EXCEPTION 'V11 contains duplicate tasks or incomplete transfer pairs';
        END IF;

        SELECT
            (SELECT COALESCE(sum(length(COALESCE(description, ''))
                               + length(COALESCE(learning_objectives, ''))
                               + length(COALESCE(typical_problems, ''))
                               + length(COALESCE(aliases, ''))), 0)
             FROM public.informatics_knowledge_nodes
             WHERE enabled = true AND library_version = 'informatics-knowledge-discipline-v6')
          + (SELECT COALESCE(sum(length(COALESCE(description, ''))
                               + length(COALESCE(learning_goal, ''))
                               + length(COALESCE(knowledge_node_codes, ''))), 0)
             FROM public.ai_standard_skill_units
             WHERE enabled = true AND library_version = 'informatics-discipline-quality-v6')
          + (SELECT COALESCE(sum(length(COALESCE(description, ''))
                               + length(COALESCE(misconception, ''))
                               + length(COALESCE(symptom, ''))
                               + length(COALESCE(repair_strategy, ''))), 0)
             FROM public.ai_standard_mistake_points
             WHERE enabled = true AND library_version = 'informatics-discipline-quality-v6')
          + (SELECT COALESCE(sum(length(COALESCE(description, ''))
                               + length(COALESCE(improvement_goal, ''))
                               + length(COALESCE(practice_strategy, ''))
                               + length(COALESCE(student_benefit, ''))
                               + length(COALESCE(teacher_explanation, ''))), 0)
             FROM public.ai_standard_improvement_points
             WHERE enabled = true AND library_version = 'informatics-discipline-quality-v6')
          + (SELECT COALESCE(sum(length(COALESCE(task_context, ''))
                               + length(COALESCE(student_task, ''))
                               + length(COALESCE(observable_evidence, ''))
                               + length(COALESCE(common_failure, ''))
                               + length(COALESCE(teacher_move, ''))
                               + length(COALESCE(student_check, ''))
                               + length(COALESCE(constraint_profile, ''))
                               + length(COALESCE(success_criteria, ''))
                               + length(COALESCE(transfer_note, ''))), 0)
             FROM public.ai_standard_application_scenarios
             WHERE enabled = true AND library_version = 'informatics-discipline-application-v2')
        INTO batch_chars;

        IF batch_chars < 100000 THEN
            RAISE EXCEPTION 'V11 effective text volume is too small: % characters', batch_chars;
        END IF;
    END IF;
END $$;
